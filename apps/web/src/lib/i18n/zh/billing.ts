import type { billing as Fr } from '../fr/billing'

/** 计数名词的两种形式：中文不分单复数，量词包含在名词中。 */
type Noun = { one: string; many: string }

const fmt = (n: number) => n.toLocaleString('zh-CN')
/** 中文不分单复数。 */
const form = (_n: number, noun: Noun) => noun.many
/** “150 额度”。 */
const credits = (n: number) => `${fmt(n)} 额度`
/** “至 2026 年 11 月 23 日”，没有日期时为空。 */
const until = (date: string | null) => (date ? `，有效期至 ${date}` : '')
/** 去掉量词，得到名词本身。 */
const bare = (noun: Noun) => noun.many.slice(1)
/** 优惠期时长，按商店的单位（默认按月）。 */
const PERIODS: Record<string, Noun> = {
  DAY: { one: '天', many: '天' },
  WEEK: { one: '周', many: '周' },
  MONTH: { one: '个月', many: '个月' },
  YEAR: { one: '年', many: '年' },
}

