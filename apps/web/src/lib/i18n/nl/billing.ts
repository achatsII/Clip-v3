/** De twee vormen van een telbaar woord: “station”, “stations”. */
type Noun = { one: string; many: string }

const fmt = (n: number) => n.toLocaleString('nl-NL')
/** In het Nederlands heeft alleen 1 het enkelvoud. */
const form = (n: number, noun: Noun) => (n !== 1 ? noun.many : noun.one)
/** “150 credits”. */
const credits = (n: number) => `${fmt(n)} ${n !== 1 ? 'credits' : 'credit'}`
/** “tot 23 november 2026”, of niets zonder datum. */
const until = (date: string | null) => (date ? ` tot ${date}` : '')
/** De winkel met zijn lidwoord: “de App Store”, “Google Play”. */
const theStore = (store: string) => (store === 'App Store' ? 'de App Store' : store)
/** De duur van het welkomstaanbod, per eenheid van de winkel (standaard de maand). */
const PERIODS: Record<string, Noun> = {
  DAY: { one: 'dag', many: 'dagen' },
  WEEK: { one: 'week', many: 'weken' },
  MONTH: { one: 'maand', many: 'maanden' },
  YEAR: { one: 'jaar', many: 'jaar' },
}

