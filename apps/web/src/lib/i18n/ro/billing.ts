const credits = (n: number) => `${fmt(n)} ${n === 1 ? 'credit' : `${de(n)}credite`}`
const until = (date: string | null) => (date ? ` până la ${date}` : '')
const inStore = (store: string) => (store === 'App Store' ? 'în App Store' : `pe ${store}`)
const times = (n: number) => (n === 1 ? 'o dată' : `de ${fmt(n)} ${de(n)}ori`)
