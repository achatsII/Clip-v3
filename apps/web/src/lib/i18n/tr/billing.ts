/** Sayılan bir adın iki biçimi: Türkçede sayıdan sonra ad tekil kalır. */
type Noun = { one: string; many: string }

const fmt = (n: number) => n.toLocaleString('tr-TR')
/** Türkçede sayıdan sonra ad değişmez. */
const form = (n: number, noun: Noun) => (n !== 1 ? noun.many : noun.one)
/** « 150 kredi ». */
const credits = (n: number) => `${fmt(n)} kredi`
/** « (23 Kasım 2026 tarihine kadar) », tarih yoksa hiçbir şey. */
const until = (date: string | null) => (date ? ` (${date} tarihine kadar)` : '')
/** Mağaza adı olduğu gibi: « App Store », « Google Play ». */
const theStore = (store: string) => store
/** Karşılama teklifinin süreleri, mağazanın birimine göre (varsayılan ay). */
