import type { billing as Fr } from '../fr/billing'

/** As duas formas de um nome que se conta: « posto », « postos ». */
type Noun = { one: string; many: string }

const fmt = (n: number) => n.toLocaleString('pt-BR')
/** Em português, só o 1 leva o singular. */
const form = (n: number, noun: Noun) => (n !== 1 ? noun.many : noun.one)
/** « 150 créditos ». */
const credits = (n: number) => `${fmt(n)} ${n !== 1 ? 'créditos' : 'crédito'}`
/** « até 23 de novembro de 2026 », ou nada sem data. */
const until = (date: string | null) => (date ? ` até ${date}` : '')
/** A loja com a preposição: « na App Store », « no Google Play ». */
const inStore = (store: string) => (store === 'App Store' ? 'na App Store' : `no ${store}`)
/** Um posto de venda com o artigo: « a App Store », « o Google Play ». */
const theStore = (store: string) => (store === 'App Store' ? 'a App Store' : `o ${store}`)
/** « da App Store », « do Google Play ». */
const ofStore = (store: string) => (store === 'App Store' ? 'da App Store' : `do ${store}`)
/** As durações da oferta de boas-vindas, por unidade da loja (o mês por padrão). */
const PERIODS: Record<string, Noun> = {
  DAY: { one: 'dia', many: 'dias' },
  WEEK: { one: 'semana', many: 'semanas' },
  MONTH: { one: 'mês', many: 'meses' },
  YEAR: { one: 'ano', many: 'anos' },
}

