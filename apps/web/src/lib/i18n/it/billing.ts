import type { billing as Fr } from '../fr/billing'

/** Le due forme di un nome che si conta: “postazione”, “postazioni”. */
type Noun = { one: string; many: string }

const fmt = (n: number) => n.toLocaleString('it-IT')
/** In italiano, solo 1 prende il singolare. */
const form = (n: number, noun: Noun) => (n !== 1 ? noun.many : noun.one)
/** “150 crediti”. */
const credits = (n: number) => `${fmt(n)} ${n !== 1 ? 'crediti' : 'credito'}`
/** “fino al 23 novembre 2026”, o niente senza data. */
const until = (date: string | null) => (date ? ` fino al ${date}` : '')
/** Il negozio con il suo articolo: “l’App Store”, “Google Play”. */
const theStore = (store: string) => (store === 'App Store' ? 'l’App Store' : store)
/** Il negozio dopo “su”: “sull’App Store”, “su Google Play”. */
const onStore = (store: string) => (store === 'App Store' ? 'sull’App Store' : `su ${store}`)
/** Le durate dell’offerta di benvenuto, per unità del negozio (il mese in mancanza d’altro). */
const PERIODS: Record<string, Noun> = {
  DAY: { one: 'giorno', many: 'giorni' },
  WEEK: { one: 'settimana', many: 'settimane' },
  MONTH: { one: 'mese', many: 'mesi' },
  YEAR: { one: 'anno', many: 'anni' },
}

