/** Tên được đếm có hai dạng (số ít, số nhiều); tiếng Việt chỉ có một dạng. */
type Noun = { one: string; many: string }

const fmt = (n: number) => n.toLocaleString('vi-VN')
/** Tiếng Việt không chia số ít và số nhiều. */
const form = (_n: number, noun: Noun) => noun.many
/** « 150 tín dụng ». */
const credits = (n: number) => `${fmt(n)} tín dụng`
/** « đến ngày 23 tháng 11 năm 2026 », hoặc không có gì khi không có ngày. */
