import type { billing as Fr } from '../fr/billing'

/** Las dos formas de un nombre que se cuenta: «puesto», «puestos». */
type Noun = { one: string; many: string }

const fmt = (n: number) => n.toLocaleString('es-MX')
/** En español, solo 1 lleva el singular. */
const form = (n: number, noun: Noun) => (n !== 1 ? noun.many : noun.one)
/** «150 créditos». */
const credits = (n: number) => `${fmt(n)} crédito${n !== 1 ? 's' : ''}`
/** «hasta el 23 de noviembre de 2026», o nada sin fecha. */
const until = (date: string | null) => (date ? ` hasta el ${date}` : '')
/** La tienda con su artículo: «la App Store», «Google Play». */
const theStore = (store: string) => (store === 'App Store' ? 'la App Store' : store)
/** Las duraciones de la oferta de bienvenida, por unidad de la tienda (el mes por defecto). */
const PERIODS: Record<string, Noun> = {
  DAY: { one: 'día', many: 'días' },
  WEEK: { one: 'semana', many: 'semanas' },
  MONTH: { one: 'mes', many: 'meses' },
  YEAR: { one: 'año', many: 'años' },
}

