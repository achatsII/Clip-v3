/** Egy számolt főnév két alakja: magyarul a szám után mindig egyes szám. */
type Noun = { one: string; many: string }

const fmt = (n: number) => n.toLocaleString('hu-HU')
/** Magyarul a számnév után a főnév egyes számban áll. */
const form = (_n: number, noun: Noun) => noun.one
/** « 150 kredit ». */
const credits = (n: number) => `${fmt(n)} kredit`
/** « (eddig: 2026. november 23.) », vagy semmi dátum nélkül. */
const until = (date: string | null) => (date ? ` (eddig: ${date})` : '')
/** Az üzlet névelővel: « az App Store », « a Google Play ». */
const theStore = (store: string) => (store === 'App Store' ? 'az App Store' : `a ${store}`)
/** Az üdvözlőajánlat időtartamai az üzlet egysége szerint (alapértelmezés: hónap). */
